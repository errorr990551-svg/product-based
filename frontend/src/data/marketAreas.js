// Returns the state and the other cities in it for a city slug, or null
export const findRegion = (slug) => {
  const matches = marketData.filter((r) => r.cities.some((c) => c.link === `/${slug}`));
  // Prefer the city's own state over the metro group when it is in both
  const region = matches.find((r) => r.state !== "Major Metro Cities") || matches[0];
  if (!region) return null;
  return { state: region.state, cities: region.cities.filter((c) => c.link !== `/${slug}`) };
};

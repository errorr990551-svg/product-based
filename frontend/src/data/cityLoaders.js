// Alternate spellings that serve the same page as the main slug.
export const cityAliases = {"anantpur": "anantapur"};

const data = {};
const pending = {};

export const hasCity = (slug) => Object.prototype.hasOwnProperty.call(loaders, slug);

// Already-downloaded data, or undefined.
export const getCity = (slug) => data[slug];

// Stable promise per slug (React's use() needs the same promise each render).
export function loadCity(slug) {
  if (!hasCity(slug)) return Promise.resolve(undefined);
  if (!pending[slug]) {
    pending[slug] = loaders[slug]().then(
      (d) => (data[slug] = d),
      (err) => {
        delete pending[slug]; // allow a retry after a failed download
        throw err;
      }
    );
  }
  return pending[slug];
}
